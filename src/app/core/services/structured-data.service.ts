import { DOCUMENT } from '@angular/common';
import { Injectable, LOCALE_ID, inject } from '@angular/core';
import { environment } from '../../../environments/environment';

/**
 * Canonical origin used for all indexable URLs. Sourced from `environment.site.baseUrl`,
 * which is also read directly by `scripts/postbuild.mjs` (BASE_URL) — the single source
 * of truth for canonical/hreflang/sitemap/structured-data URLs.
 */
const BASE_URL = environment.site.baseUrl;

/** Input required to build a `SoftwareApplication` JSON-LD entry for a tool page. */
export interface SoftwareApplicationData {
  /** Tool title (without the ` | devTools` suffix). */
  name: string;
  /** Meta description text for the tool (same value used in menu-def.ts). */
  description: string;
  /** Router link for the page, e.g. `/json-formatter`. */
  routerLink: string;
}

/**
 * Injects/removes a `<script type="application/ld+json">` structured data tag
 * into `<head>`. Intended to be called from a page component's
 * `ngOnInit`/`ngOnDestroy` to avoid duplicating this boilerplate across every
 * tool page.
 */
@Injectable({
  providedIn: 'root',
})
export class StructuredDataService {
  private readonly document = inject(DOCUMENT);
  private readonly locale = inject(LOCALE_ID);

  private script?: HTMLScriptElement;
  private breadcrumbScript?: HTMLScriptElement;

  /**
   * Adds a `SoftwareApplication` JSON-LD script tag for a tool page.
   * The `url` is derived from the current locale + routerLink, matching the
   * canonical URL format generated by `scripts/postbuild.mjs` (no trailing slash).
   */
  addSoftwareApplication(data: SoftwareApplicationData): void {
    const url = `${BASE_URL}/${this.locale}${data.routerLink}`;

    const script = this.document.createElement('script');
    script.type = 'application/ld+json';
    script.text = JSON.stringify({
      '@context': 'https://schema.org',
      '@type': 'SoftwareApplication',
      'name': data.name,
      'description': data.description,
      'applicationCategory': 'DeveloperApplication',
      'operatingSystem': 'Web',
      'url': url,
      'offers': { '@type': 'Offer', 'price': '0', 'priceCurrency': 'JPY' },
    });
    this.document.head.appendChild(script);
    this.script = script;
  }

  /** Removes the previously added script tag, if any. */
  remove(): void {
    this.script?.remove();
    this.script = undefined;
  }

  /**
   * Injects/replaces a `BreadcrumbList` JSON-LD script tag for the current
   * breadcrumb trail. Kept in a dedicated field so it never clobbers the
   * per-tool-page `SoftwareApplication` script managed by `addSoftwareApplication`/`remove`.
   *
   * Nodes without a `routerLink` (breadcrumb category labels, which have no
   * URL of their own) are omitted from `itemListElement` — every emitted
   * `ListItem` must have a valid `item` URL. The single-node dashboard trail
   * (Home only) is skipped entirely, since a one-item BreadcrumbList carries
   * no information.
   */
  setBreadcrumbList(items: { name: string; routerLink?: string }[]): void {
    this.breadcrumbScript?.remove();
    this.breadcrumbScript = undefined;
    if (items.length < 2) return;

    const script = this.document.createElement('script');
    script.type = 'application/ld+json';
    script.text = JSON.stringify({
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: items
        .filter((it) => it.routerLink)
        .map((it, i) => ({
          '@type': 'ListItem',
          position: i + 1,
          name: it.name,
          // Home's routerLink is "/" — appended naively that would double up
          // into a trailing slash ("/ja/"), the exact issue fixed for the
          // home link elsewhere (see HomeLinkDirective / issue #204).
          item: `${BASE_URL}/${this.locale}${it.routerLink === '/' ? '' : it.routerLink}`,
        })),
    });
    this.document.head.appendChild(script);
    this.breadcrumbScript = script;
  }
}
